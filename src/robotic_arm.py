    def __init__(self, safe_height_z: float = 10.0, work_height_z: float = 0.5):
        self.safe_z = safe_height_z
        self.work_z = work_height_z

    def generate_rework_plan(self, mapped_detections: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
        """
        Creates an ordered step-by-step rework sequence for the robotic controller.
        """
        plan = []
        # Sort by Tool ID to minimize tool change operations
        sorted_dets = sorted(
            mapped_detections,
            key=lambda d: self.TOOL_DEFINITIONS.get(d["class"], {}).get("tool_id", "T9")
        )

        for step_idx, det in enumerate(sorted_dets, start=1):
            cls_name = det["class"]
            tool_info = self.TOOL_DEFINITIONS.get(cls_name, {
                "tool_id": "T1",
                "tool_name": "General Micro-Rework Tool",
                "action": "Manual Inspection / Generic Rework",
                "spindle_speed": 1000,
                "feed_rate": 100,
                "dwell_ms": 200,
                "color": "#64748b",
            })

            coords = det.get("board_coord_mm", {"x": 0.0, "y": 0.0, "w": 1.0, "h": 1.0})
            est_time = round(1.5 + (tool_info["dwell_ms"] / 1000.0), 2)

            plan.append({
                "step": step_idx,
                "defect_id": det.get("id", step_idx),
                "defect_type": cls_name,
                "severity": det.get("severity", "Medium"),
                "coord_x_mm": coords["x"],
                "coord_y_mm": coords["y"],
                "width_mm": coords.get("w", 1.0),
                "height_mm": coords.get("h", 1.0),
                "tool_id": tool_info["tool_id"],
                "tool_name": tool_info["tool_name"],
                "action": tool_info["action"],
                "est_seconds": est_time,
                "color": tool_info["color"],
            })

        return plan

    def generate_gcode(
        self,
        rework_plan: List[Dict[str, Any]],
        operator_name: str = "Edge-AI Autonomous Inspector",
        job_id: str = "PCB-RWK-001"
    ) -> str:
        """
        Generates industrial-standard G-Code (ISO 6983 / RS-274) program.
        """
        lines = [
            f"; ===========================================================",
            f"; PROGRAM: {job_id}",
            f"; GENERATED BY: {operator_name}",
            f"; TOTAL DEFECTS TO REWORK: {len(rework_plan)}",
            f"; ===========================================================",
            "G21            ; Set units to millimeters",
            "G90            ; Set absolute positioning",
            "G17            ; Select XY plane",
            f"G00 Z{self.safe_z:.2f}    ; Retract to safe clearance height",
            "G28 X0 Y0      ; Home axes",
            ""
        ]

        current_tool = None
        for step in rework_plan:
            tool_id = step["tool_id"]
            if tool_id != current_tool:
                current_tool = tool_id
                lines.extend([
                    f"; -----------------------------------------------------------",
                    f"; TOOL CHANGE -> {step['tool_name']} ({tool_id})",
                    f"; -----------------------------------------------------------",
                    "M05            ; Spindle / laser off",
                    f"G00 Z{self.safe_z:.2f}",
                    f"{tool_id} M06          ; Mount tool {tool_id}",
                    ""
                ])

            x = step["coord_x_mm"]
            y = step["coord_y_mm"]
            tdef = self.TOOL_DEFINITIONS.get(step["defect_type"], {})
            rpm = tdef.get("spindle_speed", 2000)
            feed = tdef.get("feed_rate", 100)
            dwell = tdef.get("dwell_ms", 300)

            lines.extend([
                f"; Step {step['step']}: Rework {step['defect_type']} at X={x} Y={y}",
                f"G00 X{x:.3f} Y{y:.3f}          ; Rapid traverse to target",
                f"M03 S{rpm}                    ; Activate tool/laser",
                f"G01 Z{self.work_z:.3f} F{feed}           ; Lower to rework height",
                f"G04 P{dwell}                   ; Dwell for rework execution ({dwell}ms)",
                f"G00 Z{self.safe_z:.2f}               ; Retract to safe height",
                "M05                           ; Deactivate tool",
                ""
            ])

        lines.extend([
            "; ===========================================================",
            "; PROGRAM END & FINAL HOME",
            "; ===========================================================",
            f"G00 Z{self.safe_z:.2f}",
            "G28 X0 Y0",
            "M30            ; End of program",
            ""
        ])

        return "\n".join(lines)

