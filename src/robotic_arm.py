"""
Robotic Arm Rework & G-Code Generator Module
Generates automated correction toolpaths and G-Code for physical PCB rework:
- Laser ablation / micro-milling for short circuits and spurs
- Conductive dispenser for open circuits
- Micro-drill for missing drill holes / vias
"""

